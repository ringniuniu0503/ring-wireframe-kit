// Converts the design-source JSON files into src/styles/tokens.css.
// Run with: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const read = (file) => JSON.parse(readFileSync(new URL(`design-source/${file}`, root), 'utf8'))

const primitives = read('Value.tokens.json')
const semantic = read('Light.tokens.json')
const textStyles = read('text-styles.json')

// Walks a token tree and returns [path, token] pairs in file order.
function collect(node, path = []) {
  if (node && typeof node === 'object' && '$type' in node) return [[path, node]]
  return Object.entries(node)
    .filter(([key]) => !key.startsWith('$'))
    .flatMap(([key, child]) => collect(child, [...path, key]))
}

// Every CSS variable is namespaced with this prefix, matching the .rwk-* class names.
const PREFIX = 'rwk'
const cssVar = (name) => `--${PREFIX}-${name}`
const toVar = (path) => cssVar(path.join('-').toLowerCase())

function variableValue(token) {
  const alias = token.$extensions?.['com.figma.aliasData']
  if (alias) return `var(${toVar(alias.targetVariableName.split('/'))})`
  if (token.$type === 'color') return token.$value.hex.toLowerCase()
  return `${token.$value}px`
}

const variableLines = (tree) =>
  collect(tree).map(([path, token]) => `  ${toVar(path)}: ${variableValue(token)};`)

// ---------- Typography ----------
// The top-level "WF" group is the Figma style folder; it is dropped from token and class names.
const styles = collect(textStyles).map(([path, token]) => ({
  name: path.slice(1).join('-').toLowerCase(),
  figmaName: token.$extensions['com.figma.styleName'],
  fontStyle: token.$extensions['com.figma.fontStyle'],
  ...token.$value,
}))

const uniqueSorted = (values, compare) => [...new Set(values)].sort(compare)
const byNumber = (a, b) => a - b

// fontFamily may be a single name or a fallback stack (e.g. Roboto + Noto Sans TC).
// The token is named after its generic family, not a specific font, so all styles must share one stack.
const GENERIC_FAMILY = { token: 'sans', css: 'sans-serif' }
const familyStack = (fontFamily) => [fontFamily].flat()
const stacks = new Set(styles.map((s) => familyStack(s.fontFamily).join(', ')))
if (stacks.size > 1) {
  throw new Error(`Text styles use different font stacks (${[...stacks].join(' | ')}); add a token per stack.`)
}
const fontStack = familyStack(styles[0].fontFamily)
const weights = new Map(styles.map((s) => [s.fontWeight, s.fontStyle]))
const weightList = uniqueSorted([...weights.keys()], byNumber)
const sizes = uniqueSorted(styles.map((s) => s.fontSize), byNumber)
const lineHeights = uniqueSorted(styles.map((s) => s.lineHeight), byNumber)
const letterSpacings = uniqueSorted(styles.map((s) => s.letterSpacing), byNumber)

const familyVar = () => cssVar(`font-family-${GENERIC_FAMILY.token}`)
const weightVar = (weight) => cssVar(`font-weight-${weights.get(weight).toLowerCase()}`)
const sizeVar = (size) => cssVar(`font-size-${size}`)
const lineHeightVar = (lh) => cssVar(`line-height-${Math.round(lh * 100)}`)
const letterSpacingVar = (ls) => cssVar(`letter-spacing-${ls}`)
const textVar = (style, prop) => cssVar(`text-${style.name}-${prop}`)

const typographyPrimitiveLines = [
  `  ${familyVar()}: ${fontStack.map((f) => `'${f}'`).join(', ')}, ${GENERIC_FAMILY.css};`,
  ...weightList.map((w) => `  ${weightVar(w)}: ${w};`),
  ...sizes.map((s) => `  ${sizeVar(s)}: ${s}px;`),
  ...lineHeights.map((lh) => `  ${lineHeightVar(lh)}: ${lh};`),
  ...letterSpacings.map((ls) => `  ${letterSpacingVar(ls)}: ${ls}px;`),
]

const properties = [
  ['font-family', () => familyVar()],
  ['font-weight', (s) => weightVar(s.fontWeight)],
  ['font-size', (s) => sizeVar(s.fontSize)],
  ['line-height', (s) => lineHeightVar(s.lineHeight)],
  ['letter-spacing', (s) => letterSpacingVar(s.letterSpacing)],
]

const textStyleLines = styles.flatMap((s) => [
  `  /* Figma: ${s.figmaName} */`,
  ...properties.map(([prop, ref]) => `  ${textVar(s, prop)}: var(${ref(s)});`),
])

const classBlocks = styles.map((s) =>
  [
    `/* Figma: ${s.figmaName} */`,
    `.${PREFIX}-text-${s.name} {`,
    ...properties.map(([prop]) => `  ${prop}: var(${textVar(s, prop)});`),
    '}',
  ].join('\n'),
)

const css = `/*
 * Ring Wireframe Kit — Design Tokens
 * Generated by scripts/build-tokens.mjs from design-source/. Do not edit by hand; run \`npm run tokens\`.
 *
 * Layer 1 · Primitives: raw values (Value.tokens.json + base values from text-styles.json).
 * Layer 2 · Semantic / Text styles: aliases of primitives (Light.tokens.json + text-styles.json);
 *           use these in components.
 */

:root {
  /* ---------- Primitives ---------- */
${variableLines(primitives).join('\n')}

  /* ---------- Primitives · Typography ---------- */
${typographyPrimitiveLines.join('\n')}

  /* ---------- Semantic (Light) ---------- */
${variableLines(semantic).join('\n')}

  /* ---------- Text styles ---------- */
${textStyleLines.join('\n')}
}

/* ---------- Text style classes ---------- */

${classBlocks.join('\n\n')}
`

writeFileSync(new URL('src/styles/tokens.css', root), css)
console.log(`tokens.css written: ${styles.length} text styles`)
